export type MessageKey = keyof typeof messages.zh;

let currentLocale: Locale = 'zh';

export function initLocale(): void {
  const lang = vscode.workspace.getConfiguration('cursorQuota').get<string>('language');
  currentLocale = lang === 'en' ? 'en' : 'zh';
}

export function t(key: MessageKey, ...args: (string | number)[]): string {
  let msg: string = messages[currentLocale][key] || messages.zh[key] || key;
  args.forEach((arg, i) => {
    msg = msg.replace(`{${i}}`, String(arg));
  });
  return msg;
}
